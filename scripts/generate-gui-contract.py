#!/usr/bin/env python3
"""Generate argument boundaries for registered Tauri commands."""
from pathlib import Path
import argparse,json,re
ROOT=Path(__file__).resolve().parents[1]

def split_top(text):
    depth=0; start=0; result=[]
    for i,c in enumerate(text):
        if c in '(<[': depth+=1
        elif c in ')>]': depth-=1
        elif c==',' and depth==0: result.append(text[start:i].strip()); start=i+1
    result.append(text[start:].strip())
    return [part for part in result if part]

def camel(name):
    head,*tail=name.split('_'); return head+''.join(p.title() for p in tail)

lib=(ROOT/'gui/src-tauri/src/lib.rs').read_text()
handler=re.search(r'generate_handler!\[([\s\S]*?)\]',lib)
if not handler:raise SystemExit('No Tauri command registration found.')
registered={name.strip().split('::')[-1] for name in handler.group(1).split(',') if name.strip()}
commands={}
for path in sorted((ROOT/'gui/src-tauri/src').glob('*.rs')):
    source=path.read_text()
    source=re.sub(r'^\s*//[^\n]*', '', source, flags=re.M)
    for match in re.finditer(r'^\s*#\[tauri::command(?:\([^\]]*\))?\]\s*(?:#\[[^\]]*\]\s*)*(?:pub(?:\([^)]*\))?\s+)?(?:async\s+)?fn\s+(\w+)\s*\(',source,re.M):
        if match.group(1) not in registered:continue
        depth=1; end=match.end()
        while depth and end<len(source):
            depth+= (source[end]=='(')-(source[end]==')'); end+=1
        parameters={}
        for item in split_top(source[match.end():end-1]):
            if ':' not in item: continue
            name,typ=item.split(':',1); name=name.strip(); typ=typ.strip()
            if re.search(r'\b(State|AppHandle|WebviewWindow|Window)\b',typ):continue
            if not re.fullmatch(r'\w+',name):continue
            parameters[camel(name)]={'required':not typ.startswith('Option<'),'rust_type':typ}
        commands[match.group(1)]=parameters
missing=registered-set(commands)
if missing:raise SystemExit('Registered command declarations not found: '+', '.join(sorted(missing)))
out=ROOT/'gui/src/lib/command-contract.ts'
text='// Generated by scripts/generate-gui-contract.py; Rust declarations are authoritative.\n'
text+='export const commandContract = '+json.dumps(commands,ensure_ascii=False,indent=2)+' as const;\n'
text+='export type Command = keyof typeof commandContract;\n'
text+='export type CommandArgs<C extends Command> = {[K in keyof typeof commandContract[C]]?: unknown};\n'
parser=argparse.ArgumentParser()
parser.add_argument('--check',action='store_true')
if parser.parse_args().check:
    if not out.is_file() or out.read_text()!=text:
        raise SystemExit('GUI contract is stale: run npm run contract in gui/.')
    print(f'Verified {len(commands)} Tauri command contracts.')
else:
    out.write_text(text)
    print(f'Generated {len(commands)} Tauri command contracts.')
