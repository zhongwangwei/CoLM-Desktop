#!/usr/bin/env python3
"""生成 vendor/CoLM202X/Makefile 末尾的同阶段 Fortran 模块依赖块。

上游 Makefile 只靠对象在阶段变量里的排列顺序保证模块先编译，串行 make 能过、`make -j` 不安全。
这里按源码的 MODULE/USE 推出**同一阶段内**的 `.o -> .o` 前置；跨阶段的顺序已由模式规则里的
`${OBJS_SHARED}` 等前置保证，不再重复。

阶段 = Makefile 里每条 `$(VAR) : %.o : %.F90 ...` 模式规则的目标列表；变量值交给 make 自己展开
（含 `+=`、嵌套变量与 `$(addprefix ...)`），不在这里重写一遍 make 的语义。

    python3 oracle/scripts/gen_fortran_deps.py            # 重写 Makefile 里的生成块
    python3 oracle/scripts/gen_fortran_deps.py --check    # 只比对，不一致时返回 1

同步上游之后必须重跑本脚本（见 docs/upstream-bugs.md）。
"""

import argparse
import difflib
import os
import re
import shutil
import subprocess
import sys
import tempfile

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
VENDOR = os.path.join(REPO, "vendor", "CoLM202X")
MAKEFILE = os.path.join(VENDOR, "Makefile")
BEGIN = "# >>> generated by oracle/scripts/gen_fortran_deps.py -- do not edit by hand >>>"
END = "# <<< end of generated Fortran module prerequisites <<<"
MODULE_DEF = re.compile(r"^\s*module\s+(?!procedure\b)([a-z0-9_]+)\s*$", re.IGNORECASE)
USE_STMT = re.compile(r"^\s*use\s*(?:,\s*(intrinsic|non_intrinsic)\s*::|::)?\s*([a-z0-9_]+)", re.IGNORECASE)


def stage_variables(makefile_text):
    """Keep each complete target expression: a phase may combine/filter variables."""
    names = []
    for line in makefile_text.replace("\\\n", " ").splitlines():
        normalized = line.replace("${", "$(").replace("}", ")")
        match = re.match(r"^([^:\n]+?)\s*:\s*%\.o\s*:\s*%\.F90", normalized)
        if not match:
            continue
        names.append(match.group(1).strip())
    return names


def expand(variable):
    """Let make expand a phase, retaining legal defined-but-empty phases."""
    expression = f"$({variable})" if re.fullmatch(r"[A-Za-z0-9_]+", variable) else variable
    references = sorted(set(re.findall(r"\$\(([A-Za-z0-9_]+)\)", expression)))
    with open(os.path.join(VENDOR, "Makefile"), encoding="utf-8") as source:
        declared = set(re.findall(r"^\s*([A-Za-z0-9_]+)\s*[:+?]?=", source.read(), re.MULTILINE))
    env = os.environ.copy()
    env["LC_ALL"] = "C"
    command = ["make"]
    if tools := env.get("COLM_FORTRAN_DEPS_BIN"):
        names = ("make", "bash", "sh", "cpp", "awk", "printf")
        if os.name == "nt":
            names += ("cygpath",)
        binaries = {name: shutil.which(name, path=tools) for name in names}
        missing = [name for name, path in binaries.items() if path is None]
        if missing:
            raise RuntimeError(f"COLM_FORTRAN_DEPS_BIN is missing required tools: {', '.join(missing)}")
        # Only make's child processes need the POSIX tools; do not shadow MSVC's link.exe.
        env["PATH"] = tools + os.pathsep + env.get("PATH", "")
        shell = binaries["bash"]
        if os.name == "nt":
            shell = subprocess.check_output([binaries["cygpath"], "-u", shell], env=env, text=True).strip()
        command = [binaries["make"], "SHELL=" + shell]
    with tempfile.NamedTemporaryFile("w", suffix=".mk", delete=False) as helper:
        for name in references:
            # An optional phase (e.g. CaMa) can be declared inside an inactive conditional.
            if name in declared:
                continue
            helper.write(f"ifeq ($(origin {name}),undefined)\n$(error undefined phase variable {name} in {expression})\nendif\n")
        helper.write(".PHONY: __colm_deps_print\n__colm_deps_print:\n")
        helper.write(f"\t@echo __COLM_DEPS_BEGIN__\n\t@echo {expression}\n\t@echo __COLM_DEPS_END__\n")
        path = helper.name
    try:
        make_path = path
        if tools and os.name == "nt":
            make_path = subprocess.check_output([binaries["cygpath"], "-u", path], env=env, text=True).strip()
        result = subprocess.run(
            command + ["-s", "--warn-undefined-variables", "-f", "Makefile", "-f", make_path, "__colm_deps_print"],
            cwd=VENDOR, env=env, check=True, capture_output=True, text=True)
    except subprocess.CalledProcessError as error:
        raise RuntimeError(f"cannot expand phase {expression} in {MAKEFILE}: {error.stderr.strip()}") from error
    finally:
        os.unlink(path)
    if result.stderr:
        print(f"make {variable}: {result.stderr.rstrip()}", file=sys.stderr)
        warnings = re.findall(re.escape(make_path) + r":\d+: warning: undefined variable ['`]([^'`]+)['`]",
                              result.stderr)
        unknown = sorted(set(warnings) - declared)
        if unknown:
            raise RuntimeError(f"undefined variables {', '.join(unknown)} in phase {expression} in {MAKEFILE}")
    lines = result.stdout.splitlines()
    if lines.count("__COLM_DEPS_BEGIN__") != 1 or lines.count("__COLM_DEPS_END__") != 1:
        raise RuntimeError(f"missing expansion output for phase {expression} in {MAKEFILE}")
    begin, end = lines.index("__COLM_DEPS_BEGIN__"), lines.index("__COLM_DEPS_END__")
    if end <= begin:
        raise RuntimeError(f"invalid expansion output for phase {expression} in {MAKEFILE}")
    objects = " ".join(lines[begin + 1:end]).split()
    if any(not obj.endswith(".o") for obj in objects):
        raise RuntimeError(f"non-object expansion for phase {expression} in {MAKEFILE}: {objects}")
    return objects


def vpath_directories(makefile_text):
    match = re.search(r"^VPATH\s*=\s*((?:.*\\\n)*.*)$", makefile_text, re.MULTILINE)
    text = match.group(1).replace("\\\n", " ")
    return [part.strip() for part in text.split(":") if part.strip()]


def find_source(obj, directories):
    stem = obj[:-2]
    for directory in directories:
        path = os.path.join(VENDOR, directory, stem + ".F90")
        if os.path.isfile(path):
            return path
    return None


def scan(path):
    """一个源文件定义的模块与 USE 的模块（小写；`#ifdef` 两支都算）。"""
    defined, used = set(), set()
    with open(path, encoding="utf-8", errors="replace") as handle:
        for raw in handle:
            line = raw.split("!", 1)[0]
            match = MODULE_DEF.match(line)
            if match:
                defined.add(match.group(1).lower())
                continue
            match = USE_STMT.match(line)
            if match and (match.group(1) or "").lower() != "intrinsic":
                used.add(match.group(2).lower())
    return defined, used - defined


def generate():
    with open(MAKEFILE, encoding="utf-8") as handle:
        text = handle.read()
    directories = vpath_directories(text)
    lines = []
    variables = stage_variables(text)
    for variable in variables:
        objects = [obj for obj in expand(variable) if obj != "CoLM_Mkdir.o"]
        sources = {obj: find_source(obj, directories) for obj in objects}
        owner, uses = {}, {}
        for obj, path in sources.items():
            if path is None:
                continue
            defined, used = scan(path)
            uses[obj] = used
            for module in defined:
                owner.setdefault(module, obj)
        for obj in sorted(uses):
            deps = sorted({owner[m] for m in uses[obj] if m in owner and owner[m] != obj})
            if deps:
                lines.append(f"{obj}: {' '.join(deps)}")
    # 对象都写进 `.bld/`：并行时要先建好目录（order-only，不触发重编）。
    order_only = [f"{variable}: | mkdir_build" for variable in variables]
    block = [BEGIN,
             "# Same-stage MODULE/USE prerequisites (cross-stage ordering comes from the pattern",
             "# rules above).  Regenerate after every upstream sync.",
             *order_only,
             *sorted(set(lines)),
             END]
    return text, "\n".join(block) + "\n"


def splice(text, block):
    if BEGIN in text:
        start = text.index(BEGIN)
        end = text.index(END, start) + len(END) + 1
        return text[:start] + block + text[end:]
    return text.rstrip("\n") + "\n\n" + block


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="compare only; exit 1 on drift")
    args = parser.parse_args()
    text, block = generate()
    updated = splice(text, block)
    if args.check:
        if updated != text:
            print("vendor/CoLM202X/Makefile: generated Fortran module prerequisites are stale; "
                  "run oracle/scripts/gen_fortran_deps.py", file=sys.stderr)
            sys.stderr.writelines(difflib.unified_diff(
                text.splitlines(keepends=True), updated.splitlines(keepends=True),
                fromfile="committed Makefile", tofile="generated Makefile"))
            return 1
        print("generated Fortran module prerequisites are current")
        return 0
    with open(MAKEFILE, "w", encoding="utf-8") as handle:
        handle.write(updated)
    print(f"wrote {block.count(chr(10)) - 4} prerequisite lines to {MAKEFILE}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
